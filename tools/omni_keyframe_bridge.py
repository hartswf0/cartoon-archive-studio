def render_clean_keyframe_card(
    sheet_name: str,
    q_idx: int,
    flip_x: bool = False,
    pass_mode: str = "clean_ink",
    out_w: int = 1024,
    out_h: int = 1024,
) -> np.ndarray:
    """
    Renders a crystal-clear, high-resolution (`1024x1024`) isolated keyframe image
    ideal for uploading to Google Omni / Veo as a Start Frame or End Frame.
    """
    bg_col = (245, 250, 254) if pass_mode == "clean_ink" else BGR_PAPER
    canvas = np.full((out_h, out_w, 3), bg_col, dtype=np.uint8)
    render_traced_reference_cel_onto_canvas(
        canvas,
        sheet_name=sheet_name,
        q_idx=q_idx,
        cx=out_w * 0.50,
        cy=out_h * 0.52,
        target_w=out_w * 0.84,
        target_h=out_h * 0.84,
        pass_mode=pass_mode,
        is_agent=True,
        flip_x=flip_x,
        draw_prog=1.0,
    )
    return canvas


def export_all_omni_keyframe_packs() -> dict:
    """
    Exports all 16 Start/End Keyframe pairs (`1024x1024` PNGs in both Clean Ink and Gouache),
    writes `omni_keyframe_packs/OMNI_VIDEO_PROMPTS.md` and `omni_manifest.json`, and builds
    `preview/omni_start_end_keyframe_prompts_sheet.png`.
    """
    PACKS_DIR.mkdir(parents=True, exist_ok=True)
    (PACKS_DIR / "clean_ink_pairs").mkdir(parents=True, exist_ok=True)
    (PACKS_DIR / "gouache_pairs").mkdir(parents=True, exist_ok=True)
    (PACKS_DIR / "videos").mkdir(parents=True, exist_ok=True)
    PREVIEW_DIR.mkdir(parents=True, exist_ok=True)

    manifest_shots = []
    md_lines = [
        "# Google Omni / Veo Start & End Keyframe Prompt Pack (`16` Contiguous Animation Beats)",
        "",
        "Drop any **Start Frame** (`*_start.png`) and **End Frame** (`*_end.png`) pair into Google Omni / Veo along with its **Motion Prompt** below.",
        "Once you download the generated `.mp4` clip into `omni_keyframe_packs/videos/`, run:",
        "```bash",
        "python3 tools/omni_keyframe_bridge.py --trace-video omni_keyframe_packs/videos/<your_clip.mp4> --shot-id 1",
        "```",
        "to automatically extract the frames and trace them into **Pass 1 (Non-Photo Blue + Onion Skin)**, **Pass 2 (Speedball B-5 India Ink Cleanup)**, and **Pass 3 (Watertight Gouache Multiplane Cel)**!",
        "",
        "---",
        "",
    ]

    contact_rows = []
    current_row = []

    for spec in OMNI_16_SHOT_SPECS:
        sid = spec["shot_id"]
        code = spec["code"]
        s_sheet, s_q, s_flip = spec["start_pose"]
        e_sheet, e_q, e_flip = spec["end_pose"]

        # 1. Render 1024x1024 Clean Ink Start & End frames
        ink_start = render_clean_keyframe_card(s_sheet, s_q, flip_x=s_flip, pass_mode="clean_ink", out_w=1024, out_h=1024)
        ink_end = render_clean_keyframe_card(e_sheet, e_q, flip_x=e_flip, pass_mode="clean_ink", out_w=1024, out_h=1024)
        ink_start_path = PACKS_DIR / "clean_ink_pairs" / f"{code}_start.png"
        ink_end_path = PACKS_DIR / "clean_ink_pairs" / f"{code}_end.png"
        cv2.imwrite(str(ink_start_path), ink_start)
        cv2.imwrite(str(ink_end_path), ink_end)

        # 2. Render 1024x1024 Gouache Colored Start & End frames
        gou_start = render_clean_keyframe_card(s_sheet, s_q, flip_x=s_flip, pass_mode="gouache", out_w=1024, out_h=1024)
        gou_end = render_clean_keyframe_card(e_sheet, e_q, flip_x=e_flip, pass_mode="gouache", out_w=1024, out_h=1024)
        gou_start_path = PACKS_DIR / "gouache_pairs" / f"{code}_start.png"
        gou_end_path = PACKS_DIR / "gouache_pairs" / f"{code}_end.png"
        cv2.imwrite(str(gou_start_path), gou_start)
        cv2.imwrite(str(gou_end_path), gou_end)

        shot_entry = {
            "shot_id": sid,
            "code": code,
            "title": spec["title"],
            "action_verbs": spec["action_verbs"],
            "omni_prompt": spec["omni_prompt"],
            "clean_ink_start": str(ink_start_path),
            "clean_ink_end": str(ink_end_path),
            "gouache_start": str(gou_start_path),
            "gouache_end": str(gou_end_path),
        }
        manifest_shots.append(shot_entry)

        md_lines.extend([
            f"## Shot {sid:02d}: {spec['title']} (`{code}`)",
            f"- **Start Frame (Clean Ink)**: [`{code}_start.png`](file://{ink_start_path})",
            f"- **End Frame (Clean Ink)**: [`{code}_end.png`](file://{ink_end_path})",
            f"- **Start Frame (Gouache Cel)**: [`{code}_start.png`](file://{gou_start_path})",
            f"- **End Frame (Gouache Cel)**: [`{code}_end.png`](file://{gou_end_path})",
            f"- **Animator Action Breakdown**: {spec['action_verbs']}",
            "- **Copy-Paste Google Omni / Veo Prompt**:",
            "```text",
            spec["omni_prompt"],
            "```",
            "",
        ])

        # Build visual contact card (`620x260`) showing `[START FRAME] ---> [PROMPT] ---> [END FRAME]`
        card_w, card_h = 620, 265
        card = np.full((card_h, card_w, 3), (242, 246, 250), dtype=np.uint8)
        cv2.rectangle(card, (0, 0), (card_w, 30), (32, 42, 58), -1)
        cv2.putText(
            card,
            f"SHOT {sid:02d} ({code}): {spec['title'].upper()[:44]}",
            (10, 21), cv2.FONT_HERSHEY_SIMPLEX, 0.46, (242, 248, 255), 1, cv2.LINE_AA,
        )
        thumb_sz = 168
        t_start = cv2.resize(gou_start, (thumb_sz, thumb_sz), interpolation=cv2.INTER_AREA)
        t_end = cv2.resize(gou_end, (thumb_sz, thumb_sz), interpolation=cv2.INTER_AREA)
        card[38:38 + thumb_sz, 12:12 + thumb_sz] = t_start
        card[38:38 + thumb_sz, card_w - 12 - thumb_sz:card_w - 12] = t_end
        cv2.rectangle(card, (12, 38), (12 + thumb_sz, 38 + thumb_sz), (42, 118, 68), 2)
        cv2.rectangle(card, (card_w - 12 - thumb_sz, 38), (card_w - 12, 38 + thumb_sz), (48, 72, 196), 2)
        cv2.putText(card, "START KEYFRAME", (24, 54), cv2.FONT_HERSHEY_SIMPLEX, 0.38, (32, 96, 52), 1, cv2.LINE_AA)
        cv2.putText(card, "END KEYFRAME", (card_w - thumb_sz, 54), cv2.FONT_HERSHEY_SIMPLEX, 0.38, (42, 62, 182), 1, cv2.LINE_AA)

        # Center prompt box + arrow
        mid_x0, mid_x1 = 190, card_w - 190
        cv2.arrowedLine(card, (mid_x0 + 12, 64), (mid_x1 - 12, 64), (48, 78, 196), 2, cv2.LINE_AA, tipLength=0.08)
        cv2.putText(card, "OMNI VIDEO PROMPT", (mid_x0 + 44, 56), cv2.FONT_HERSHEY_SIMPLEX, 0.38, (48, 78, 196), 1, cv2.LINE_AA)

        words = spec["omni_prompt"].split()
        lines, cur = [], ""
        for w_tok in words:
            if len(cur) + len(w_tok) + 1 <= 34:
                cur = f"{cur} {w_tok}".strip()
            else:
                lines.append(cur)
                cur = w_tok
        if cur:
            lines.append(cur)
        for li, ln in enumerate(lines[:7]):
            cv2.putText(card, ln, (mid_x0 + 6, 86 + li * 17), cv2.FONT_HERSHEY_SIMPLEX, 0.34, BGR_INK, 1, cv2.LINE_AA)

        # Bottom action verbs bar
        cv2.rectangle(card, (8, card_h - 48), (card_w - 8, card_h - 8), (226, 236, 244), -1)
        cv2.rectangle(card, (8, card_h - 48), (card_w - 8, card_h - 8), BGR_INK, 1)
        act_txt = spec["action_verbs"]
        cv2.putText(card, act_txt[:82], (14, card_h - 30), cv2.FONT_HERSHEY_SIMPLEX, 0.34, BGR_INK, 1, cv2.LINE_AA)
        if len(act_txt) > 82:
            cv2.putText(card, act_txt[82:164], (14, card_h - 14), cv2.FONT_HERSHEY_SIMPLEX, 0.34, BGR_INK, 1, cv2.LINE_AA)

        cv2.rectangle(card, (0, 0), (card_w - 1, card_h - 1), BGR_INK, 2)
        current_row.append(card)
        if len(current_row) == 2:
            contact_rows.append(np.hstack(current_row))
            current_row = []

    sheet_grid = np.vstack(contact_rows)
    banner_h = 54
    banner = np.full((banner_h, sheet_grid.shape[1], 3), (24, 28, 36), dtype=np.uint8)
    cv2.putText(
        banner,
        "GOOGLE OMNI / VEO KEYFRAME BRIDGE: 16 START & END KEYFRAME PAIRS + MOTION PROMPTS -> HAND-DRAWN CEL TRACER",
        (16, 35), cv2.FONT_HERSHEY_SIMPLEX, 0.62, (242, 248, 255), 2, cv2.LINE_AA,
    )
    full_sheet = np.vstack([banner, sheet_grid])
    sheet_path = PREVIEW_DIR / "omni_start_end_keyframe_prompts_sheet.png"
    cv2.imwrite(str(sheet_path), full_sheet)
    if ARTIFACT_DIR.exists():
        shutil.copy2(sheet_path, ARTIFACT_DIR / "omni_start_end_keyframe_prompts_sheet.png")

    md_path = PACKS_DIR / "OMNI_VIDEO_PROMPTS.md"
    md_path.write_text("\n".join(md_lines))
    manifest_path = PACKS_DIR / "omni_manifest.json"
    manifest_path.write_text(json.dumps({"shots": manifest_shots, "contact_sheet": str(sheet_path)}, indent=2))
    print(f"[Omni Keyframe Bridge] Exported 16 Start/End Keyframe pairs to {PACKS_DIR}")
    print(f"[Omni Keyframe Bridge] Saved prompt book to {md_path}")
    print(f"[Omni Keyframe Bridge] Saved visual contact sheet to {sheet_path}")
    return {"shots": len(manifest_shots), "sheet_path": str(sheet_path), "md_path": str(md_path)}


def trace_video_to_hand_drawn_cels(
    video_path: str,
    shot_id: int = 1,
    max_frames: int = 16,
    sheet_tag: str = "nib_omni_traced",
) -> dict:
    """
    Stage 2: Takes any video clip (`.mp4` / `.mov` / `.webm`) generated by Google Omni / Veo
    from our Start/End keyframes, samples `max_frames` frames across the clip, and runs our
    High-Resolution Calligraphic Ink & Topological Gouache Cel Tracer on every frame to produce:
      - Pass 1: Non-Photo Blue construction underdrawing + Onion-Skin ghosting
      - Pass 2: Crisp variable-width Speedball B-5 India Ink cleanup on warm bond paper
      - Pass 3: Watertight topological gouache cel fills!
    Saves a 3-Pass Traced Flipbook Contact Sheet and individual traced PNG cels.
    """
    vpath = Path(video_path)
    if not vpath.exists():
        raise FileNotFoundError(f"Video file not found: {vpath}")

    cap = cv2.VideoCapture(str(vpath))
    raw_frames = []
    while True:
        ret, frame = cap.read()
        if not ret:
            break
        raw_frames.append(frame)
    cap.release()

    if not raw_frames:
        raise RuntimeError(f"Could not decode any frames from video: {vpath}")

    idxs = np.linspace(0, len(raw_frames) - 1, min(max_frames, len(raw_frames))).astype(int)
    sampled = [raw_frames[i] for i in idxs]

    out_dir = PACKS_DIR / f"traced_shot_{shot_id:02d}"
    out_dir.mkdir(parents=True, exist_ok=True)

    pass1_cells, pass2_cells, pass3_cells = [], [], []
    prev_ink_bin = None

    for f_i, bgr in enumerate(sampled):
        # Normalize video frame into `512x512` clean cel space
        h, w = bgr.shape[:2]
        side = min(h, w)
        y0 = (h - side) // 2
        x0 = (w - side) // 2
        crop = cv2.resize(bgr[y0:y0 + side, x0:x0 + side], (512, 512), interpolation=cv2.INTER_AREA)

        gray = cv2.cvtColor(crop, cv2.COLOR_BGR2GRAY)
        ink_alpha = np.clip((205.0 - gray.astype(np.float32)) / 125.0, 0.0, 1.0)
        ink_bin = (gray < 175).astype(np.uint8) * 255

        sil_mask, gouache_bgr, _, _ = _segment_cel_gouache_regions(
            sheet_tag, gray, ink_bin, ink_alpha, is_agent=True
        )
        sil_f = (sil_mask.astype(np.float32) / 255.0)[..., None]
        ink_f = ink_alpha[..., None]

        # Pass 1: Non-Photo Blue + Sepia Onion-Skin of previous video frame
        p1 = np.full((512, 512, 3), BGR_PAPER, dtype=np.float32)
        if prev_ink_bin is not None:
            ghost = (prev_ink_bin.astype(np.float32) / 255.0)[..., None] * 0.42
            onion_col = np.array((128, 148, 212), dtype=np.float32).reshape(1, 1, 3)
            p1 = p1 * (1.0 - ghost) + onion_col * ghost
        blue_col = np.array(BGR_NONPHOTO_BLUE, dtype=np.float32).reshape(1, 1, 3)
        p1 = p1 * (1.0 - ink_f * 0.88) + blue_col * (ink_f * 0.88)
        p1_u8 = np.clip(p1, 0, 255).astype(np.uint8)

        # Pass 2: Speedball B-5 India Ink Cleanup on Cream Bond Paper
        p2 = np.full((512, 512, 3), BGR_PAPER, dtype=np.float32)
        paper_cel = np.array((244, 251, 255), dtype=np.float32).reshape(1, 1, 3)
        ink_col = np.array(BGR_INK, dtype=np.float32).reshape(1, 1, 3)
        p2 = p2 * (1.0 - sil_f) + paper_cel * sil_f
        p2 = p2 * (1.0 - ink_f) + ink_col * ink_f
        p2_u8 = np.clip(p2, 0, 255).astype(np.uint8)

        # Pass 3: Watertight Topological Gouache Cel
        p3 = np.full((512, 512, 3), BGR_PAPER, dtype=np.float32)
        p3 = p3 * (1.0 - sil_f) + gouache_bgr.astype(np.float32) * sil_f
        p3 = p3 * (1.0 - ink_f) + ink_col * ink_f
        p3_u8 = np.clip(p3, 0, 255).astype(np.uint8)

        prev_ink_bin = ink_bin.copy()

        cv2.imwrite(str(out_dir / f"frame_{f_i:03d}_pass1_blue.png"), p1_u8)
        cv2.imwrite(str(out_dir / f"frame_{f_i:03d}_pass2_ink.png"), p2_u8)
        cv2.imwrite(str(out_dir / f"frame_{f_i:03d}_pass3_gouache.png"), p3_u8)

        if len(pass1_cells) < 8:
            tw, th = 220, 220
            pass1_cells.append(cv2.resize(p1_u8, (tw, th), interpolation=cv2.INTER_AREA))
            pass2_cells.append(cv2.resize(p2_u8, (tw, th), interpolation=cv2.INTER_AREA))
            pass3_cells.append(cv2.resize(p3_u8, (tw, th), interpolation=cv2.INTER_AREA))

    strip = np.vstack([
        np.hstack(pass1_cells),
        np.hstack(pass2_cells),
        np.hstack(pass3_cells),
    ])
    strip_path = out_dir / f"shot_{shot_id:02d}_traced_3pass_flipbook.png"
    cv2.imwrite(str(strip_path), strip)
    print(f"[Omni Keyframe Bridge] Traced {len(sampled)} video frames into 3 hand-drawn passes at {out_dir}")
    return {"frames_traced": len(sampled), "out_dir": str(out_dir), "flipbook_sheet": str(strip_path)}


