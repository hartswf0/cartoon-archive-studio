"""
Google Omni / Veo Start-End Keyframe Pack Exporter & Video-to-Hand-Drawn Cel Tracer
(`tools/omni_keyframe_bridge.py`)
====================================================================================
Implements the two-stage "Start/End Keyframes -> Google Omni Video -> Hand-Drawn Cel Tracing"
pipeline:

  STAGE 1 (`--export-packs`, default):
    Exports 16 high-resolution Start Frame (`shot_XX_start.png`) + End Frame (`shot_XX_end.png`)
    keyframe pairs (in both Clean Speedball Ink Line-Art and Watertight Gouache Cel variants)
    into `omni_keyframe_packs/`, alongside:
      - `omni_keyframe_packs/OMNI_VIDEO_PROMPTS.md`: Copy-pasteable Google Omni / Veo prompts
        for every Start -> End keyframe pair (specifying exact physical verbs, arcs, timing,
        overlap, and 2D hand-drawn ink line-art consistency).
      - `omni_keyframe_packs/omni_manifest.json`: Machine-readable shot manifest.
      - `preview/omni_start_end_keyframe_prompts_sheet.png`: Visual contact sheet showing all
        16 Start Frame -> Motion Prompt -> End Frame pairs.

  STAGE 2 (`--trace-video <video_path> [--shot-id <1..16>]`):
    Ingests any video clip generated by Google Omni / Veo from a Start/End keyframe pair,
    extracts its intermediate frames at 24fps (Key -> Breakdown -> In-Between), and runs our
    High-Resolution Calligraphic Ink & Topological Gouache Cel Tracer on every extracted video
    frame to produce:
      - Pass 1: Non-Photo Blue construction underdrawing + Onion-Skin ghosts + motion arcs
      - Pass 2: Crisp variable-width Speedball B-5 India Ink cleanup on warm bond paper
      - Pass 3: Watertight topological gouache cel fills composited into the 7-plane studio!
"""

