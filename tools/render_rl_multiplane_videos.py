#!/usr/bin/env python3
"""
Renders all 8 shots from the Argon RL Policy Evolved `shot.json` files into:
  1. 7-Plane Multiplane Cartoon frames (`640x480`) using `render_multiplane_stage_frame`
     from `scion_multiplane_studio.py` with:
       - Pass A/B Inside-Out Construction (`build_pass_ab_construction`)
       - Pass C Watertight Surgical SAM Cel (`masks`)
       - Pass D Clean Argon RL Episode 3 Evolved Doodle Strokes (`cast.frames`)
       - Pass E 7-Plane Depth-Stratified Environment (`objects`)
       - Pass F Animated Secondary Action (`build_animated_secondary_strokes`)
  2. Audio-muxed `shots/<slug>/comparison.mp4`
  3. Master showcase reel `Cartoon_Archive_Living_Doodles_Showcase.mp4`
  4. Animated GIFs in `/Users/gaia/.gemini/antigravity/brain/113f482f-cd73-450c-be83-dd0bcb11307b/`:
       - `pure_cartoon_<slug>.gif` (Full-frame 7-Plane Multiplane Cartoon)
       - `cartoon_<slug>.gif` (3-Panel Live Animated Strip: Archival | Argon RL Match/Fail Overlay | 7-Plane Cartoon)
"""

import json
import subprocess
from pathlib import Path
import cv2
import numpy as np
from PIL import Image

from scion_multiplane_studio import (
    build_animated_secondary_strokes,
    build_pass_ab_construction,
    render_7plane_sheet_preview,
    render_multiplane_stage_frame,
)

ROOT = Path("/Users/gaia/WORLDBUILDING-TERMS/cartoon_archive_studio")
SHOTS_DIR = ROOT / "shots"
ART_DIR = Path("/Users/gaia/.gemini/antigravity/brain/113f482f-cd73-450c-be83-dd0bcb11307b")

SHOT_ORDER = [
    "giraffe-walks-past",
    "dog",
    "horse",
    "rabbit",
    "bicycle",
    "helicopter",
    "sailboat",
    "windmill",
]


def scale_strokes_to_640(strokes_list, W_target=640, H_target=480):
    # Check max coordinate to avoid double-scaling if already in 640x480
    all_x = [p[0] for f_st in strokes_list for st in f_st for p in st]
    all_y = [p[1] for f_st in strokes_list for st in f_st for p in st]
    if not all_x:
        return strokes_list
    # In 480x360, ground_tick or coords stay <= 490; in 640x480 we scale by 4/3
    scale = 4.0 / 3.0 if (max(all_x) <= 495.0 and max(all_y) <= 370.0) else 1.0
    if abs(scale - 1.0) < 1e-4:
        return strokes_list
    out = []
    for f_st in strokes_list:
        f_out = []
        for st in f_st:
            f_out.append([[round(p[0] * scale, 1), round(p[1] * scale, 1)] for p in st])
        out.append(f_out)
    return out


def main():
    concat_list_path = ROOT / "concat_list.txt"
    concat_lines = []

    for slug in SHOT_ORDER:
        sdir = SHOTS_DIR / slug
        shot_data = json.loads((sdir / "shot.json").read_text())
        dsa = json.loads((sdir / "depth_sam_analysis.json").read_text())
        rl_log = json.loads((sdir / "rl_policy_log.json").read_text())
        f_paths = sorted((sdir / "frames-src").glob("f*.png"))

        # Scale Argon RL Episode 3 strokes and SAM cel polygons from 480x360 to 640x480
        cast_frames_640 = scale_strokes_to_640(shot_data["cast"]["frames"])
        masks_640 = scale_strokes_to_640(shot_data["masks"])
        shot_data["cast"]["frames"] = cast_frames_640
        shot_data["masks"] = masks_640

        cam = shot_data["camera"]
        objects = shot_data["objects"]
        active_keys = shot_data["cast"]["active_key_per_frame"]
        xsheet = shot_data["xsheet"]
        breakdown_indices = shot_data["cast"].get("breakdown_indices", [4, 15, 26])

        # Recompute Pass A/B construction and Pass F animated secondary action for the surgical SAM boxes
        sec_frames = []
        pass_ab_frames = []
        pass_ab_strokes_flat = []
        for f in range(33):
            cur_bb = dsa["frames"][f]["bbox"]
            sec_f = build_animated_secondary_strokes(slug, f, cur_bb, cam[f])
            ab_f = build_pass_ab_construction(slug, cur_bb, f, cam[f])
            sec_frames.append(sec_f)
            pass_ab_frames.append(ab_f)
            pass_ab_strokes_flat.append(ab_f.get("gesture", []) + ab_f.get("masses", []))

        shot_data["secondary_frames"] = sec_frames
        shot_data["construction_frames"] = pass_ab_strokes_flat
        (sdir / "shot.json").write_text(json.dumps(shot_data, separators=(",", ":")))

        # Update 7-plane stack preview sheet with the Argon RL Evolved character
        render_7plane_sheet_preview(sdir, objects, cast_frames_640, masks_640, cam)
        if (sdir / "planes" / "multiplane-stack.png").exists():
            cv2.imwrite(
                str(ART_DIR / f"stack_{slug}.png"),
                cv2.imread(str(sdir / "planes" / "multiplane-stack.png")),
            )

        # Load animated overlay GIF frames generated by argon_rl_doodle_engine.py
        ov_gif_path = ART_DIR / f"overlay_cartoon_{slug}.gif"
        ov_pil = Image.open(str(ov_gif_path))
        ov_frames_bgr = []
        try:
            while True:
                rgb_ov = np.array(ov_pil.convert("RGB"))
                ov_frames_bgr.append(cv2.cvtColor(rgb_ov, cv2.COLOR_RGB2BGR))
                ov_pil.seek(ov_pil.tell() + 1)
        except EOFError:
            pass

        pure_pil_frames = []
        trio_pil_frames = []

        raw_mp4 = sdir / "comparison_raw.mp4"
        comp_mp4 = sdir / "comparison.mp4"
        vw = cv2.VideoWriter(str(raw_mp4), cv2.VideoWriter_fourcc(*"mp4v"), 16.0, (1280, 480))

        for f in range(33):
            bgr_src = cv2.imread(str(f_paths[min(f, len(f_paths) - 1)]))
            left_640 = cv2.resize(bgr_src, (640, 480), interpolation=cv2.INTER_AREA)
            bb = [int(round(v)) for v in dsa["frames"][f]["bbox"]]
            cv2.rectangle(left_640, (bb[0], bb[1]), (bb[2], bb[3]), (40, 225, 110), 2)
            cv2.rectangle(left_640, (8, 8), (385, 34), (20, 20, 20), -1)
            cv2.putText(
                left_640,
                f"ARCHIVAL + SURGICAL SAM IoU={dsa['frames'][f]['sam_iou']:.2f} | F{f+1:02d}",
                (14, 26),
                cv2.FONT_HERSHEY_SIMPLEX,
                0.44,
                (245, 245, 245),
                1,
                cv2.LINE_AA,
            )

            right_640 = render_multiplane_stage_frame(
                f,
                slug,
                cam,
                objects,
                cast_frames_640,
                masks_640,
                sec_frames,
                pass_ab_frames,
                active_keys,
                xsheet[f],
                show_construction=(f in breakdown_indices),
            )
            # Top-right Argon RL Reward badge
            cv2.rectangle(right_640, (375, 8), (632, 34), (22, 20, 18), -1)
            cv2.putText(
                right_640,
                f"ARGON RL R={rl_log['mean_reward_ep3']:.2f} MATCH={int(rl_log['mean_edge_recall_ep3']*100)}%",
                (382, 26),
                cv2.FONT_HERSHEY_SIMPLEX,
                0.42,
                (110, 245, 130),
                1,
                cv2.LINE_AA,
            )

            comp = np.hstack([left_640, right_640])
            cv2.line(comp, (640, 0), (640, 480), (18, 20, 22), 2)
            vw.write(comp)
            vw.write(comp)

            # Pure cartoon frame (480x360 for crisp fast-loading inline GIF)
            c_480 = cv2.resize(right_640, (480, 360), interpolation=cv2.INTER_AREA)
            c_rgb = cv2.cvtColor(c_480, cv2.COLOR_BGR2RGB)
            pure_pil_frames.append(Image.fromarray(c_rgb).quantize(colors=96, method=Image.Quantize.MEDIANCUT))

            # 3-Panel Trio Strip (Archival | Argon RL Match/Fail Overlay | 7-Plane Multiplane Cartoon)
            ov_bgr = ov_frames_bgr[min(f, len(ov_frames_bgr) - 1)] if ov_frames_bgr else c_480
            trio_bgr = np.hstack([
                cv2.resize(left_640, (300, 225), interpolation=cv2.INTER_AREA),
                cv2.resize(ov_bgr, (300, 225), interpolation=cv2.INTER_AREA),
                cv2.resize(right_640, (300, 225), interpolation=cv2.INTER_AREA),
            ])
            trio_rgb = cv2.cvtColor(trio_bgr, cv2.COLOR_BGR2RGB)
            trio_pil_frames.append(Image.fromarray(trio_rgb).quantize(colors=96, method=Image.Quantize.MEDIANCUT))

        vw.release()

        wav_path = sdir / "soundtrack.wav"
        subprocess.run(
            [
                "/Users/gaia/anaconda3/bin/ffmpeg",
                "-y",
                "-i",
                str(raw_mp4),
                "-i",
                str(wav_path),
                "-c:v",
                "libx264",
                "-pix_fmt",
                "yuv420p",
                "-crf",
                "19",
                "-c:a",
                "aac",
                "-b:a",
                "128k",
                "-shortest",
                str(comp_mp4),
            ],
            check=True,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        raw_mp4.unlink(missing_ok=True)
        concat_lines.append(f"file '{comp_mp4}'\n")

        pure_gif = ART_DIR / f"pure_cartoon_{slug}.gif"
        pure_pil_frames[0].save(
            str(pure_gif),
            save_all=True,
            append_images=pure_pil_frames[1:],
            duration=125,
            loop=0,
            optimize=True,
        )

        trio_gif = ART_DIR / f"cartoon_{slug}.gif"
        trio_pil_frames[0].save(
            str(trio_gif),
            save_all=True,
            append_images=trio_pil_frames[1:],
            duration=125,
            loop=0,
            optimize=True,
        )
        print(
            f"[Render RL Video] {slug:18s} | pure_gif={pure_gif.stat().st_size//1024}KB | trio_gif={trio_gif.stat().st_size//1024}KB"
        )

    concat_list_path.write_text("".join(concat_lines))
    master_mp4 = ROOT / "Cartoon_Archive_Living_Doodles_Showcase.mp4"
    subprocess.run(
        [
            "/Users/gaia/anaconda3/bin/ffmpeg",
            "-y",
            "-f",
            "concat",
            "-safe",
            "0",
            "-i",
            str(concat_list_path),
            "-c:v",
            "libx264",
            "-pix_fmt",
            "yuv420p",
            "-c:a",
            "aac",
            str(master_mp4),
        ],
        check=True,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    print(f"[Render RL Video] Master showcase reel updated: {master_mp4}")


if __name__ == "__main__":
    main()
